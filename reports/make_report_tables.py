"""Builds reports/report_tables.md from the committed logs, so every number in the report can be traced to a run.

Nothing here is typed in by hand: tables come from results/logs/*.json|csv and results/tables/*.csv, and the
Bayesian search ranges are read from the search code itself (src/models/tune_xgb.py).

Usage: python reports/make_report_tables.py
"""

import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
LOGS, TABLES = ROOT / "results" / "logs", ROOT / "results" / "tables"

MODELS = [
    ("logreg", "Logistic Regression"),
    ("dtree", "Decision Tree"),
    ("rf", "Random Forest"),
    ("xgb", "XGBoost (default settings)"),
    ("mlp", "MLP"),
]
OBJECTIVE = {
    "logreg": "Log loss (binary cross-entropy) with an L2 penalty on the weights",
    "dtree": "Gini impurity, minimised greedily at each split",
    "rf": "Gini impurity in each tree; trees are fitted on bootstrap samples and averaged",
    "xgb": "Logistic loss with L2 (lambda) and L1 (alpha) penalties on leaf weights and a minimum split gain (gamma)",
    "xgb_tuned": "Same as XGBoost: logistic loss with L2/L1 penalties and a minimum split gain",
    "mlp": "Log loss (binary cross-entropy) minimised with Adam and an L2 penalty (alpha)",
}


def load(key):
    return json.loads((LOGS / f"{key}_summary.json").read_text())


def md(df, floatfmt=4):
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join(["---"] * len(cols)) + "|"]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(f"{v:.{floatfmt}f}" if isinstance(v, float) else str(v) for v in r) + " |")
    return "\n".join(out)


def search_space():
    """Record the ranges that tune_xgb.suggest() asks for, by calling it with a recording stand-in for the trial."""
    from src.models.tune_xgb import suggest

    class Rec:
        def __init__(self):
            self.rows = []

        def suggest_int(self, name, lo, hi, step=1):
            self.rows.append((name, f"integer {lo} to {hi}" + (f", step {step}" if step != 1 else "")))
            return lo

        def suggest_float(self, name, lo, hi, log=False):
            self.rows.append((name, f"{lo} to {hi}" + (" (log scale)" if log else "")))
            return lo

    r = Rec()
    suggest(r)
    return pd.DataFrame(r.rows, columns=["Hyper-parameter", "Range searched"])


def main():
    blocks = {}
    S = {k: load(k) for k, _ in MODELS + [("xgb_tuned", "")]}
    parts = ["# Report tables (generated by reports/make_report_tables.py from the committed logs)\n"]

    # 3.1 overall comparison: use the table written by src/models/compare.py
    cmp_ = pd.read_csv(TABLES / "model_comparison.csv")
    parts += [
        "## 3.1 Overall model comparison\n",
        "Source: results/tables/model_comparison.csv (python -m src.models.compare). CV = 5-fold trip-grouped on the training trips; "
        "student-test columns come from one fit on all training trips.\n",
        md(cmp_),
        "",
    ]
    blocks["overall"] = md(cmp_)

    # per-model evidence
    rows = []
    for k, name in MODELS + [("xgb_tuned", "XGBoost (tuned)")]:
        s = S[k]
        rows.append(
            {
                "Model": name,
                "CV macro F1": s["cv_macro_f1_mean"],
                "CV std": s["cv_macro_f1_std"],
                "Train Top-1": s["student_train_top1_acc"],
                "Student Top-1": s["student_top1_acc"],
                "Train macro F1": s["student_train_macro_f1"],
                "Student macro F1": s["student_macro_f1"],
                "Student log loss": s["student_log_loss"],
                "Fit time (s)": s["final_fit_seconds"],
                "Inference (ms/point)": s["student_inference_ms_per_point"],
            }
        )
    parts += [
        "## 3.2 Per-model evidence (train vs student-test, for the over/under-fitting question)\n",
        "'Train' = the same fitted model scored on its own training trips. A large train-to-student gap points to overfitting; "
        "low scores on both point to underfitting.\n",
        md(pd.DataFrame(rows)),
        "",
    ]
    blocks["evidence"] = md(pd.DataFrame(rows))
    cfg = pd.DataFrame(
        [
            {
                "Model": name,
                "Hyper-parameters (initial / final values)": json.dumps(S[k]["params"]),
                "Optimisation objective": OBJECTIVE[k],
            }
            for k, name in MODELS + [("xgb_tuned", "XGBoost (tuned)")]
        ]
    )
    parts += ["## 3.2 Configuration and objective per model\n", md(cfg), ""]
    blocks["config"] = md(cfg)
    folds = []
    for k, name in MODELS + [("xgb_tuned", "XGBoost (tuned)")]:
        f = pd.read_csv(LOGS / f"{k}_cv_folds.csv")
        if "max_depth" in f.columns and k == "dtree":
            f = f[f.max_depth.astype(str) == str(S[k]["params"]["max_depth"])]
        folds.append({"Model": name, **{f"fold {i}": v for i, v in enumerate(f.test_macro_f1.round(4).tolist())}})
    parts += ["## 3.3 Macro F1 per CV fold (same folds for every model)\n", md(pd.DataFrame(folds)), ""]
    blocks["folds"] = md(pd.DataFrame(folds))

    # 4 Bayesian optimisation
    best = json.loads((LOGS / "xgb_best_params.json").read_text())
    trials = pd.read_csv(LOGS / "xgb_tuning_trials.csv")
    states = trials.state.value_counts().to_dict()
    parts += [
        "## 4. Bayesian optimisation of XGBoost\n",
        f"Optuna TPE sampler, seed {best['seed']}, objective = mean macro F1 over the 5 trip-grouped CV folds on the training trips "
        f"(maximised). Trials run: {best['n_trials']} ({states.get('COMPLETE', 0)} completed, {states.get('PRUNED', 0)} stopped early by the "
        f"median pruner). Trial 0 is the untuned default.\n",
        md(search_space()),
        "",
        "Best parameters (trial %d):\n" % best["trial"],
        "```json",
        json.dumps(best["params"], indent=1),
        "```\n",
    ]
    blocks["tuning_intro"] = (
        f"Optuna TPE sampler, seed {best['seed']}, objective = mean macro F1 over the 5 trip-grouped CV folds on the training trips "
        f"(maximised). Trials run: {best['n_trials']} ({states.get('COMPLETE', 0)} completed, {states.get('PRUNED', 0)} stopped early by the "
        f"median pruner). Trial 0 is the untuned default."
    )
    blocks["tuning_space"] = md(search_space())
    blocks["tuning_best"] = "```json\n" + json.dumps(best["params"], indent=1) + "\n```"
    t = []
    for k, name in [("xgb", "XGBoost (untuned)"), ("xgb_tuned", "XGBoost (tuned)")]:
        s = S[k]
        t.append(
            {
                "Model": name,
                "CV macro F1": s["cv_macro_f1_mean"],
                "Student Top-1": s["student_top1_acc"],
                "Student macro F1": s["student_macro_f1"],
                "Student log loss": s["student_log_loss"],
                "Inference (ms/point)": s["student_inference_ms_per_point"],
            }
        )
    parts += ["Untuned vs tuned, same folds and partitions:\n", md(pd.DataFrame(t)), ""]
    blocks["tuning_cmp"] = md(pd.DataFrame(t))
    a, b = (
        pd.read_csv(LOGS / "xgb_cv_folds.csv").test_macro_f1.to_numpy(),
        pd.read_csv(LOGS / "xgb_tuned_cv_folds.csv").test_macro_f1.to_numpy(),
    )
    perfold = (
        f"Tuned minus untuned CV macro F1 per fold: {', '.join(f'{x:+.4f}' for x in (b - a))} "
        f"(tuned better on {(b > a).sum()} of {len(a)} folds; fold standard deviation is {S['xgb_tuned']['cv_macro_f1_std']:.4f})."
    )
    parts += [perfold + "\n"]
    blocks["tuning_perfold"] = perfold

    # 5 HMM
    h = json.loads((LOGS / "hmm_xgb_tuned_summary.json").read_text())
    st = h["student_test"]
    rows = []
    for key, name in [
        ("classifier_only", "Classifier only (XGBoost tuned)"),
        ("hmm_default", "Classifier + HMM (default decoder settings)"),
        ("hmm_tuned", "Classifier + HMM (tuned decoder settings)"),
    ]:
        m = st[key]["metrics"]
        rows.append(
            {
                "Method": name,
                "Top-1": m["top1_acc"],
                "Macro F1": m["macro_f1"],
                "Route continuity": m["route_continuity"],
                "Continuity (real arc changes only)": m["route_continuity_transitions"],
                "Route F1": m["route_f1_mean"],
            }
        )
    parts += [
        "## 5. HMM and Viterbi\n",
        f"Decoder parameters were tuned on out-of-fold training probabilities ({h['tuning']['trials']} Optuna trials on "
        f"{h['tuning']['n_train_trips']} training trips, objective: {h['tuning']['objective']}) and then evaluated once on student-test.\n",
        md(pd.DataFrame(rows)),
        "",
        "Tuned decoder parameters:\n",
        "```json",
        json.dumps(h["decoder_params"], indent=1),
        "```\n",
    ]
    blocks["hmm_intro"] = (
        f"Decoder parameters were tuned on out-of-fold training probabilities ({h['tuning']['trials']} Optuna trials on "
        f"{h['tuning']['n_train_trips']} training trips, objective: {h['tuning']['objective']}) and then evaluated once on student-test."
    )
    blocks["hmm_table"] = md(pd.DataFrame(rows))
    blocks["hmm_params"] = "```json\n" + json.dumps(h["decoder_params"], indent=1) + "\n```"
    pt = pd.read_csv(TABLES / "hmm_vs_classifier_xgb_tuned_per_trip.csv")
    pt["trip_id"] = pt.trip_id.astype(str).str.zfill(8)
    pt["Top-1 change"] = pt.top1_hmm - pt.top1_classifier
    pt["Route F1 change"] = pt.route_f1_hmm - pt.route_f1_classifier
    pt = pt.rename(
        columns={
            "trip_id": "Trip",
            "n_points": "Points",
            "top1_classifier": "Top-1 classifier",
            "top1_hmm": "Top-1 HMM",
            "route_f1_classifier": "Route F1 classifier",
            "route_f1_hmm": "Route F1 HMM",
        }
    )
    parts += [
        "Per student-test trip (tuned decoder):\n",
        md(
            pt[
                [
                    "Trip",
                    "Points",
                    "Top-1 classifier",
                    "Top-1 HMM",
                    "Top-1 change",
                    "Route F1 classifier",
                    "Route F1 HMM",
                    "Route F1 change",
                ]
            ]
        ),
        "",
    ]
    blocks["hmm_pertrip"] = md(
        pt[
            [
                "Trip",
                "Points",
                "Top-1 classifier",
                "Top-1 HMM",
                "Top-1 change",
                "Route F1 classifier",
                "Route F1 HMM",
                "Route F1 change",
            ]
        ]
    )
    parts += [
        "Reference route continuity for comparison (the reference route itself is not perfectly connected): see the "
        "route_breaks column of results/tables/data_quality.csv and results/tables/route_continuity_diagnostic.csv.\n"
    ]

    # confusion matrices
    cm = TABLES / "confusion_matrices.csv"
    if cm.exists():
        parts += [
            "## Confusion matrices (student-test)\n",
            md(pd.read_csv(cm)),
            "",
            "Figure: results/figures/confusion_matrices.png\n",
        ]
        blocks["confusion"] = md(pd.read_csv(cm))

    # data facts
    dq = pd.read_csv(TABLES / "data_quality.csv", dtype={"trip_id": str})
    tq = pd.read_csv(TABLES / "trip_quality.csv", dtype={"trip_id": str})
    facts = (
        dq.groupby("partition")
        .agg(
            trips=("trip_id", "count"),
            gps_points=("n_points", "sum"),
            min_points=("n_points", "min"),
            max_points=("n_points", "max"),
            trips_with_gap_over_60s=("n_gaps_gt_60s", lambda x: int((x > 0).sum())),
            trips_with_route_breaks=("route_breaks", lambda x: int((x > 0).sum())),
        )
        .reset_index()
    )
    excl = tq[tq.label_frac < 0.5]
    parts += [
        "## 2.2 Data facts (results/tables/data_quality.csv, trip_quality.csv)\n",
        md(facts),
        "",
        "Excluded from training and evaluation (fewer than half of the GPS points could be labelled): "
        + ", ".join(f"{r.partition} trip {r.trip_id} ({100 * r.label_frac:.0f}% labelled)" for r in excl.itertuples())
        + ".\n",
    ]

    blocks["datafacts"] = md(facts)
    blocks["excluded"] = ", ".join(
        f"{r.partition} trip {r.trip_id} ({100 * r.label_frac:.0f}% labelled)" for r in excl.itertuples()
    )
    (ROOT / "reports" / "report_tables.md").write_text("\n".join(parts))
    print("wrote reports/report_tables.md")
    template = ROOT / "reports" / "report_template.md"
    if template.exists():  # fill {{name}} placeholders; edit the template, not the output
        text = template.read_text()
        missing = [k for k in set(__import__("re").findall(r"\{\{(\w+)\}\}", text)) if k not in blocks]
        assert not missing, f"template uses unknown blocks: {missing}"
        for k, v in blocks.items():
            text = text.replace("{{" + k + "}}", v)
        (ROOT / "reports" / "TECHNICAL_REPORT.md").write_text(text)
        print("wrote reports/TECHNICAL_REPORT.md from reports/report_template.md")


if __name__ == "__main__":
    main()
